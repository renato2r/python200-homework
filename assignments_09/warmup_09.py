from azure.storage.blob import ContainerClient

def list_container(container_client: ContainerClient) -> None:
    """
    Lists and prints the name and size (in bytes) of every blob 
    inside the provided container.
    
    :param container_client: An instantiated Azure ContainerClient object.
    :return: None
    """
    # Iterate through the generator returned by list_blobs()
    for blob in container_client.list_blobs():
        print(f"{blob.name} ({blob.size} bytes)")
        
