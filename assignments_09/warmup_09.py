def upload_text(container_client: ContainerClient, blob_name: str, text: str) -> None:
    """
    Encodes a Python string as UTF-8 and uploads it to Azure Blob Storage,
    overwriting any existing blob with the same name.
    
    :param container_client: An instantiated Azure ContainerClient object.
    :param blob_name: The destination path/name of the blob in the container.
    :param text: The raw string content to upload.
    :return: None
    """
    # Convert the Python string into UTF-8 bytes
    data_bytes = text.encode('utf-8')
    
    # Upload the data, explicitly enabling the overwrite flag
    container_client.upload_blob(name=blob_name, data=data_bytes, overwrite=True)